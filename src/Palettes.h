/*
 *  Palette collection
 *
 * Each palette consists of colors.
 * A color is represented as an RGB triplet - 3 bytes:
 * Red, Green, Blue.
 * Each palette begins with the triplet 0xff, 0xff, 0xff,
 * and ends with the triplet 0x00, 0x00, 0x00.
 * The palette itself is located between these "brackets".
 * The size of a palette may vary.
 * There may be any number of palettes. You can freely add or delete palettes: include yours, delete unused ones, etc.
 * The library processes them dynamically.
 * Each palette has to be stretched or squeezed to the number of colors equal to the LED count of the strip.
 * For example, if you are using an LED strip of 100 LEDs, you can operate with 100 colors regardless of the palette you selected.
 * Color #0 is the first color of the palette; the number of the last color is equal to the LED count - 1
 * (color numbering starts from 0).
 * The end of all palettes is marked by one more triplet:
 * 0x00, 0x00, 0x00
 * The enum name may be used instead of the palette #.
 * The array is const, so it is stored in flash memory, not in RAM.
 * Each byte may be defined as a decimal, octal or hexadecimal value (anything allowed by C++ syntax).
 * Each color component must be less than 256 (fit in a byte).
 * To insert your palette, add triplets to the list,
 * like:
 *    0xff, 0xff, 0xff,
 *    palette colors...
 *    0x00, 0x00, 0x00,
 *
 */

